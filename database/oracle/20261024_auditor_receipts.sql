-- Run once as DIGITALIZACION (or substitute the schema in the application config).
-- Oracle 11gR2 compatible. This keeps external auditor folders out of PLANILLA_DIGITAL.

CREATE TABLE DIGITALIZACION.SPD_AUDITORIA_RECEPCION (
  AER_ID                    VARCHAR2(40 BYTE)   NOT NULL,
  AER_JOB_ID                VARCHAR2(64 BYTE)   NOT NULL,
  AER_CARPETA               VARCHAR2(512 BYTE)  NOT NULL,
  AER_SERVICIO              VARCHAR2(30 BYTE)   NOT NULL,
  AER_MES                   VARCHAR2(2 BYTE)    NOT NULL,
  AER_ANIO                  VARCHAR2(4 BYTE)    NOT NULL,
  AER_ESTADO                VARCHAR2(30 BYTE)   NOT NULL,
  AER_USUARIO               VARCHAR2(128 BYTE)  NOT NULL,
  AER_FECHA_REGISTRO        DATE                DEFAULT SYSDATE NOT NULL,
  AER_FECHA_ACTUALIZACION   DATE                DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_SPD_AUD_RECEPCION PRIMARY KEY (AER_ID),
  CONSTRAINT CK_SPD_AUD_REC_ESTADO CHECK (AER_ESTADO IN ('PENDIENTE_PLANILLA','VINCULADO'))
);

CREATE INDEX DIGITALIZACION.IX_SPD_AUD_REC_PERIODO
  ON DIGITALIZACION.SPD_AUDITORIA_RECEPCION (AER_ANIO, AER_MES, AER_SERVICIO);
CREATE INDEX DIGITALIZACION.IX_SPD_AUD_REC_JOB
  ON DIGITALIZACION.SPD_AUDITORIA_RECEPCION (AER_JOB_ID);

CREATE TABLE DIGITALIZACION.SPD_AUDITORIA_RECEPCION_PDF (
  AED_UUID                  VARCHAR2(24 BYTE)   NOT NULL,
  AER_ID                    VARCHAR2(40 BYTE)   NOT NULL,
  AED_VERSION               NUMBER(6)           NOT NULL,
  AED_PDI_ID                NUMBER,
  AED_NOMBRE_ARCHIVO        VARCHAR2(512 BYTE)  NOT NULL,
  AED_NOMBRE_ORIGEN         VARCHAR2(512 BYTE)  NOT NULL,
  AED_RUTA                  VARCHAR2(2000 BYTE) NOT NULL,
  AED_SHA256                VARCHAR2(64 BYTE)   NOT NULL,
  AED_ESTADO                VARCHAR2(20 BYTE)   NOT NULL,
  AED_USUARIO               VARCHAR2(128 BYTE)  NOT NULL,
  AED_FECHA_REGISTRO        DATE                DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_SPD_AUD_REC_PDF PRIMARY KEY (AED_UUID, AED_VERSION),
  CONSTRAINT FK_SPD_AUD_REC_PDF FOREIGN KEY (AER_ID)
    REFERENCES DIGITALIZACION.SPD_AUDITORIA_RECEPCION (AER_ID),
  CONSTRAINT CK_SPD_AUD_REC_PDF_EST CHECK (AED_ESTADO IN ('VIGENTE','REEMPLAZADO','ELIMINADO'))
);

CREATE INDEX DIGITALIZACION.IX_SPD_AUD_PDF_RECEPCION
  ON DIGITALIZACION.SPD_AUDITORIA_RECEPCION_PDF (AER_ID, AED_ESTADO);
CREATE INDEX DIGITALIZACION.IX_SPD_AUD_PDF_PDI
  ON DIGITALIZACION.SPD_AUDITORIA_RECEPCION_PDF (AED_PDI_ID);

